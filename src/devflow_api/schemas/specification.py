"""Typed inputs and provider output for Wave 2 specifications."""

from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

type InputText = Annotated[str, StringConstraints(max_length=4000)]
type ArtifactType = Literal["requirements", "design", "tasks"]
type Severity = Literal["Critical", "High", "Medium", "Low", "Informational"]
type Dimension = Literal[
    "completeness",
    "consistency",
    "testability",
    "security_privacy",
    "architecture_compatibility",
    "edge_cases",
    "dependency_assumptions",
    "scope_creep",
]

ARTIFACT_TYPES: tuple[ArtifactType, ...] = ("requirements", "design", "tasks")
SEVERITIES: tuple[Severity, ...] = ("Critical", "High", "Medium", "Low", "Informational")
AI_REVIEW_DISCLAIMER = (
    "AI review findings are suggestions generated by a language model. They may be incomplete, "
    "incorrect, or inconsistent. Human review is required before approval."
)


class SpecificationRequestCreate(BaseModel):
    model_config = ConfigDict(extra="forbid", hide_input_in_errors=True)

    title: str = Field(min_length=1, max_length=200)
    description: str = Field(min_length=1, max_length=4000)
    business_goal: InputText | None = None
    functional_requirements: list[InputText] = Field(default_factory=list, max_length=100)
    nonfunctional_constraints: list[InputText] = Field(default_factory=list, max_length=100)
    acceptance_criteria: list[InputText] = Field(default_factory=list, max_length=100)
    repo_context: str | None = Field(default=None, max_length=262144)
    clarifying_questions: list[InputText] = Field(default_factory=list, max_length=100)
    workflow_run_id: int | None = Field(default=None, gt=0)
    workflow_step_id: int | None = Field(default=None, gt=0)


class SpecificationOutputSchema(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, hide_input_in_errors=True)

    requirements_md: str = Field(min_length=50)
    design_md: str = Field(min_length=50)
    tasks_md: str = Field(min_length=50)

    def artifacts(self) -> dict[ArtifactType, str]:
        return {
            "requirements": self.requirements_md,
            "design": self.design_md,
            "tasks": self.tasks_md,
        }


class AIReviewFinding(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, hide_input_in_errors=True)

    severity: Severity
    dimension: Dimension
    finding_text: str = Field(min_length=1, max_length=4000)
    location: str = Field(min_length=1, max_length=512)
    recommendation: str = Field(min_length=1, max_length=4000)


class ReviewFinding(AIReviewFinding):
    source: Literal["deterministic", "ai"]


class ReviewOutputSchema(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, hide_input_in_errors=True)

    findings: list[AIReviewFinding] = Field(max_length=100)


class MCPContextRequest(BaseModel):
    """Selection subject to the operator's configured MCP policy."""

    model_config = ConfigDict(extra="forbid", frozen=True, hide_input_in_errors=True)

    server: str = Field(min_length=1, max_length=256)
    tool: str = Field(min_length=1, max_length=256)
    arguments: dict[str, object] = Field(default_factory=dict)
    required: bool = False
